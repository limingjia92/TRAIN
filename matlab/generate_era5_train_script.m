function value = normalize_text_input(value,name)
% Accept character vectors and scalar MATLAB strings without requiring the
% newer string class in the public TRAIN interface.
if isa(value,'string')
    if ~isscalar(value)
        error('generate_era5_train_script:InvalidTextInput', ...
            '%s must be scalar.',name);
    end
    value = char(value);
end
if ~ischar(value)
    error('generate_era5_train_script:InvalidTextInput', ...
        '%s must be a character vector or scalar string.',name);
end
value = strtrim(value);
if isempty(value)
    error('generate_era5_train_script:InvalidTextInput', ...
        '%s must not be empty.',name);
end
end


function literal = python_string_literal(value)
% Return a double-quoted Python literal safe for Windows or POSIX paths.
value = strrep(value,'\','\\');
value = strrep(value,'"','\"');
value = strrep(value,sprintf('\r'),'\r');
value = strrep(value,sprintf('\n'),'\n');
literal = ['"' value '"'];
end
