function [] = generate_era5_train_script(output_dir,N,W,S,E,request_manifest)
%GENERATE_ERA5_TRAIN_SCRIPT Generate the stable resumable ERA5 downloader for TRAIN.
%
%   generate_era5_train_script(output_dir,N,W,S,E,request_manifest)
%
% INPUTS
%   output_dir       - TRAIN ERA5 root directory. Final files are written as
%                      <output_dir>/YYYYMMDD/ggapYYYYMMDDHHMM.nc
%   N,W,S,E          - CDS sub-area bounds [North, West, South, East]
%   request_manifest - Text file containing exact required ERA5 epochs, one
%                      YYYYMMDDHHMM value per line (normally ERA5_requests.txt
%                      generated by aps_era5_files.m).
%
% OUTPUT
%   Writes download_ERA5_train.py in output_dir. Review and run manually:
%
%       python download_ERA5_train.py
%
% DESIGN
%   Exact ERA5 epochs from Phase 2 remain the single source of truth. This
%   permanently fixes the historical 23:xx -> next-day 00:00 omission.
%
%   The primary batch strategy restores the efficient TRAIN-linux idea while
%   retaining the stabilized manifest/resume framework:
%     - calendar dates sharing the same exact UTC-hour set may be combined
%       across months/years;
%     - default maximum is 20 dates/request, based on successful production
%       use after 60-date requests exceeded CDS request-size limits;
%     - the generated downloader uses an exact CDS "date" list, so no unwanted
%       year/month/day Cartesian combinations are introduced;
%     - if CDS reports a request-size/cost limit, the batch is automatically
%       bisected (20 -> 10 -> 5 ...), without user intervention;
%     - if exact-date requests are persistently rejected by a CDS deployment,
%       the downloader automatically falls back to conservative per-month
%       year/month/day/time requests using the current catalogue-style schema.
%
%   Reliability features retained from Phase-3 v1:
%     - validate and reuse already-complete TRAIN ggap*.nc files;
%     - .part downloads and atomic final writes;
%     - validate batch NetCDF content before splitting;
%     - resumable splitting and final completeness checks;
%     - recognize valid_time/time and current/legacy pressure aliases;
%     - bounded retry/backoff for transient failures;
%     - quarantine invalid files instead of silently deleting them;
%     - ERA5_download_status.txt and ERA5_missing_after_download.txt;
%     - no global TLS/SSL warning suppression.
%
% HISTORY
%   Jan 2026  MJ  Initial TRAIN-linux batch downloader:
%                dates.txt + two fixed times; arbitrary date batches.
%
%   22/08/2026 MJ  Phase-3 v1 stabilization:
%                exact manifest, cross-day fix, current CDS schema, monthly
%                exact grouping, validation, atomic writes and resume support.
%
%   22/08/2026 MJ  Phase-3 final batching optimization:
%                - restore cross-month large-batch efficiency using exact dates;
%                - set evidence-based default MAX_DATES_PER_REQUEST=20;
%                - add automatic binary split for CDS request-size limits;
%                - retain monthly year/month/day/time as compatibility fallback;
%                - fix Python datetime.utcnow() deprecation by using UTC-aware
%                  datetime.now(timezone.utc);
%                - retain all v1 validation/resume/atomic-write safeguards.
%
% NOTE
%   This function only GENERATES the Python downloader. It never submits a CDS
%   request itself. Python dependencies are cdsapi, xarray and pandas.
%
% See also: aps_era5_files, aps_era5_ECMWF_Python, aps_load_era.

if nargin~=6
    error('generate_era5_train_script:InvalidInputCount', ...
        ['Expected six inputs: output_dir,N,W,S,E,request_manifest. ' ...
         'This is the stabilized Phase-3 interface.']);
end

output_dir = normalize_text_input(output_dir,'output_dir');
request_manifest = normalize_text_input(request_manifest,'request_manifest');

bounds = [N W S E];
if ~isnumeric(bounds) || numel(bounds)~=4 || any(~isfinite(double(bounds)))
    error('generate_era5_train_script:InvalidArea', ...
        'N, W, S and E must be finite numeric scalars.');
end
N = double(N);
W = double(W);
S = double(S);
E = double(E);

if N<S || N>90 || S<-90
    error('generate_era5_train_script:InvalidArea', ...
        'Latitude bounds must satisfy -90 <= S <= N <= 90.');
end

if exist(request_manifest,'file')~=2
    error('generate_era5_train_script:MissingManifest', ...
        'ERA5 request manifest does not exist: %s',request_manifest);
end

if exist(output_dir,'dir')~=7
    [status,msg] = mkdir(output_dir);
    if ~status
        error('generate_era5_train_script:CreateDirectoryFailed', ...
            'Cannot create output directory %s: %s',output_dir,msg);
    end
end

py_script_path = fullfile(output_dir,'download_ERA5_train.py');
fid = fopen(py_script_path,'w');
if fid<0
    error('generate_era5_train_script:OpenFailed', ...
        'Cannot create Python downloader: %s',py_script_path);
end

% Store Python as literal lines so Python percent/braces never become MATLAB
% fprintf directives.
py_lines = {
    '#!/usr/bin/env python3';
    '"""';
    'TRAIN ERA5 batch downloader generated by generate_era5_train_script.m.';
    '';
    'Reads an exact YYYYMMDDHHMM request manifest, groups exact calendar dates';
    'across months into moderate CDS requests, splits returned NetCDF files into';
    'TRAIN-compatible per-epoch ggap*.nc files, and safely resumes interrupted runs.';
    '';
    'Primary request mode:';
    '  - exact "date" list + shared UTC time set';
    '  - default 20 calendar dates per request';
    '  - adaptive binary splitting when CDS reports request-size/cost limits';
    '';
    'Compatibility fallback:';
    '  - if exact-date requests are persistently rejected, fall back automatically';
    '    to current year/month/day/time requests grouped safely within each month';
    '"""';
    '';
    'import hashlib';
    'import os';
    'import shutil';
    'import sys';
    'import time';
    'import zipfile';
    'from collections import defaultdict';
    'from datetime import datetime, timezone';
    '';
    'try:';
    '    import cdsapi';
    '    import pandas as pd';
    '    import xarray as xr';
    'except ImportError as exc:';
    '    raise SystemExit(';
    '        "Missing Python dependency: %s. Required packages: cdsapi, xarray, pandas."';
    '        % exc';
    '    )';
    '';
    'DATASET = "reanalysis-era5-pressure-levels"';
    'WORK_DIR = @@WORK_DIR@@';
    'REQUESTS_FILE = @@REQUESTS_FILE@@';
    'AREA = [@@N@@, @@W@@, @@S@@, @@E@@]  # N, W, S, E';
    '';
    '# Evidence-based default from TRAIN-linux production use. Larger requests';
    '# can be faster when accepted, but 60 dates previously exceeded CDS limits.';
    '# If a 20-date request is still too large for a region/server state, the';
    '# script automatically bisects it until CDS accepts the request.';
    'MAX_DATES_PER_REQUEST = 20';
    'MAX_RETRIES = 3';
    'RETRY_WAIT_SECONDS = 30';
    'KEEP_BATCH_FILES = False';
    '';
    'VARIABLES = ["geopotential", "relative_humidity", "temperature"]';
    'PRESSURE_LEVELS = [';
    '    "1", "2", "3", "5", "7", "10", "20", "30", "50", "70",';
    '    "100", "125", "150", "175", "200", "225", "250", "300",';
    '    "350", "400", "450", "500", "550", "600", "650", "700",';
    '    "750", "775", "800", "825", "850", "875", "900", "925",';
    '    "950", "975", "1000",';
    ']';
    '';
    'TIME_ALIASES = ("valid_time", "time")';
    'PRESSURE_ALIASES = ("pressure_level", "level", "isobaricInhPa")';
    'LATITUDE_ALIASES = ("latitude", "lat")';
    'LONGITUDE_ALIASES = ("longitude", "lon")';
    'TEMP_ALIASES = ("t", "temperature")';
    'RH_ALIASES = ("r", "relative_humidity")';
    'GEOPOT_ALIASES = ("z", "geopotential")';
    '';
    '';
    'class RequestTooLarge(RuntimeError):';
    '    pass';
    '';
    '';
    'def utc_now_text():';
    '    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")';
    '';
    '';
    'def utc_stamp():';
    '    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")';
    '';
    '';
    'def ensure_work_dir():';
    '    os.makedirs(WORK_DIR, exist_ok=True)';
    '';
    '';
    'def parse_manifest():';
    '    if not os.path.isfile(REQUESTS_FILE):';
    '        raise RuntimeError("Request manifest not found: %s" % REQUESTS_FILE)';
    '';
    '    epochs = []';
    '    seen = set()';
    '    with open(REQUESTS_FILE, "r", encoding="utf-8") as handle:';
    '        for lineno, raw in enumerate(handle, 1):';
    '            token = raw.strip()';
    '            if not token or token.startswith("#"):';
    '                continue';
    '            if len(token) != 12 or not token.isdigit():';
    '                raise RuntimeError(';
    '                    "Invalid manifest entry at line %d: %r. Expected YYYYMMDDHHMM."';
    '                    % (lineno, token)';
    '                )';
    '            try:';
    '                dt = datetime.strptime(token, "%Y%m%d%H%M")';
    '            except ValueError as exc:';
    '                raise RuntimeError(';
    '                    "Invalid date/time at line %d: %s (%s)" % (lineno, token, exc)';
    '                )';
    '            if dt.minute != 0:';
    '                raise RuntimeError(';
    '                    "ERA5 pressure-level data are hourly; minute must be 00: %s" % token';
    '                )';
    '            if token not in seen:';
    '                seen.add(token)';
    '                epochs.append(dt)';
    '';
    '    if not epochs:';
    '        raise RuntimeError("Request manifest contains no ERA5 epochs.")';
    '';
    '    epochs.sort()';
    '    return epochs';
    '';
    '';
    'def epoch_id(dt):';
    '    return dt.strftime("%Y%m%d%H%M")';
    '';
    '';
    'def target_path(dt):';
    '    day_dir = os.path.join(WORK_DIR, dt.strftime("%Y%m%d"))';
    '    return os.path.join(day_dir, "ggap%s.nc" % epoch_id(dt))';
    '';
    '';
    'def find_name(container, aliases):';
    '    names = set(container)';
    '    for alias in aliases:';
    '        if alias in names:';
    '            return alias';
    '    return None';
    '';
    '';
    'def dataset_time_name(ds):';
    '    name = find_name(ds.coords, TIME_ALIASES)';
    '    if name is None:';
    '        name = find_name(ds.variables, TIME_ALIASES)';
    '    return name';
    '';
    '';
    'def normalize_timestamp(value):';
    '    ts = pd.Timestamp(value)';
    '    if ts.tzinfo is not None:';
    '        ts = ts.tz_convert(None)';
    '    return ts.to_pydatetime().replace(tzinfo=None)';
    '';
    '';
    'def dataset_epoch_ids(ds):';
    '    time_name = dataset_time_name(ds)';
    '    if time_name is None:';
    '        raise RuntimeError("NetCDF has neither valid_time nor time.")';
    '';
    '    values = ds[time_name].values';
    '    values = values.reshape(-1) if hasattr(values, "reshape") else [values]';
    '    ids = []';
    '    for value in values:';
    '        ids.append(epoch_id(normalize_timestamp(value)))';
    '    return time_name, ids';
    '';
    '';
    'def dataset_has_train_fields(ds):';
    '    checks = [';
    '        find_name(ds.variables, TEMP_ALIASES),';
    '        find_name(ds.variables, RH_ALIASES),';
    '        find_name(ds.variables, GEOPOT_ALIASES),';
    '        find_name(ds.variables, PRESSURE_ALIASES),';
    '        find_name(ds.variables, LATITUDE_ALIASES),';
    '        find_name(ds.variables, LONGITUDE_ALIASES),';
    '    ]';
    '    return all(name is not None for name in checks)';
    '';
    '';
    'def validate_train_file(path, expected_dt=None):';
    '    if not os.path.isfile(path) or os.path.getsize(path) <= 0:';
    '        return False';
    '';
    '    try:';
    '        with xr.open_dataset(path) as ds:';
    '            if not dataset_has_train_fields(ds):';
    '                return False';
    '            _, ids = dataset_epoch_ids(ds)';
    '            if expected_dt is not None:';
    '                expected = epoch_id(expected_dt)';
    '                if len(ids) != 1 or ids[0] != expected:';
    '                    return False';
    '        return True';
    '    except Exception:';
    '        return False';
    '';
    '';
    'def quarantine(path, reason):';
    '    if not os.path.exists(path):';
    '        return';
    '    stamp = utc_stamp()';
    '    new_path = "%s.invalid_%s" % (path, stamp)';
    '    counter = 1';
    '    while os.path.exists(new_path):';
    '        new_path = "%s.invalid_%s_%d" % (path, stamp, counter)';
    '        counter += 1';
    '    os.replace(path, new_path)';
    '    print("  Quarantined invalid file (%s): %s" % (reason, new_path))';
    '';
    '';
    'def filter_missing(epochs):';
    '    missing = []';
    '    valid_existing = 0';
    '';
    '    for dt in epochs:';
    '        path = target_path(dt)';
    '        if validate_train_file(path, dt):';
    '            valid_existing += 1';
    '            continue';
    '        if os.path.exists(path):';
    '            quarantine(path, "failed TRAIN NetCDF validation")';
    '        partial = path + ".part"';
    '        if os.path.exists(partial):';
    '            os.remove(partial)';
    '        missing.append(dt)';
    '';
    '    print("Manifest epochs       : %d" % len(epochs))';
    '    print("Valid existing files  : %d" % valid_existing)';
    '    print("Epochs still missing  : %d" % len(missing))';
    '    return missing';
    '';
    '';
    'def hours_by_calendar_date(epochs):';
    '    result = defaultdict(set)';
    '    for dt in epochs:';
    '        result[dt.date()].add(dt.strftime("%H:%M"))';
    '    return result';
    '';
    '';
    'def make_exact_group(dates, times):';
    '    dates = sorted(dates)';
    '    times = tuple(sorted(times))';
    '    expected = []';
    '    for date_value in dates:';
    '        for time_text in times:';
    '            hour = int(time_text[:2])';
    '            minute = int(time_text[3:5])';
    '            expected.append(';
    '                datetime(date_value.year, date_value.month, date_value.day, hour, minute)';
    '            )';
    '    expected.sort()';
    '    return {';
    '        "dates": dates,';
    '        "times": list(times),';
    '        "epochs": expected,';
    '    }';
    '';
    '';
    'def build_exact_groups(epochs):';
    '    # A CDS request with an exact date list and a shared time set returns the';
    '    # exact Cartesian product we need. Dates with different required hour sets';
    '    # are never mixed, which preserves 23:xx -> next-day 00:00 correctness.';
    '    grouped_dates = defaultdict(list)';
    '    for date_value, times in hours_by_calendar_date(epochs).items():';
    '        grouped_dates[tuple(sorted(times))].append(date_value)';
    '';
    '    groups = []';
    '    for times in sorted(grouped_dates):';
    '        dates = sorted(grouped_dates[times])';
    '        for start in range(0, len(dates), MAX_DATES_PER_REQUEST):';
    '            groups.append(';
    '                make_exact_group(';
    '                    dates[start:start + MAX_DATES_PER_REQUEST],';
    '                    times,';
    '                )';
    '            )';
    '    groups.sort(key=lambda g: g["epochs"][0])';
    '    return groups';
    '';
    '';
    'def build_month_groups(epochs):';
    '    # Conservative compatibility fallback using the current web-form style';
    '    # year/month/day/time schema. Restricting each group to one year-month';
    '    # avoids unwanted Cartesian over-selection.';
    '    grouped_days = defaultdict(list)';
    '    for date_value, times in hours_by_calendar_date(epochs).items():';
    '        key = (date_value.year, date_value.month, tuple(sorted(times)))';
    '        grouped_days[key].append(date_value.day)';
    '';
    '    groups = []';
    '    for key in sorted(grouped_days):';
    '        year, month, times = key';
    '        days = sorted(set(grouped_days[key]))';
    '        dates = [datetime(year, month, day).date() for day in days]';
    '        groups.append(make_exact_group(dates, times))';
    '    return groups';
    '';
    '';
    'def split_group(group):';
    '    dates = group["dates"]';
    '    if len(dates) <= 1:';
    '        return None';
    '    middle = len(dates) // 2';
    '    return (';
    '        make_exact_group(dates[:middle], group["times"]),';
    '        make_exact_group(dates[middle:], group["times"]),';
    '    )';
    '';
    '';
    'def group_tag(group, mode):';
    '    payload = ",".join(epoch_id(dt) for dt in group["epochs"]).encode("ascii")';
    '    digest = hashlib.sha1(payload).hexdigest()[:10]';
    '    first = group["dates"][0].strftime("%Y%m%d")';
    '    last = group["dates"][-1].strftime("%Y%m%d")';
    '    return "%s_%s_%s_%s" % (mode, first, last, digest)';
    '';
    '';
    'def batch_path(group, mode):';
    '    return os.path.join(WORK_DIR, "era5_batch_%s.nc" % group_tag(group, mode))';
    '';
    '';
    'def common_request():';
    '    return {';
    '        "product_type": ["reanalysis"],';
    '        "variable": VARIABLES,';
    '        "pressure_level": PRESSURE_LEVELS,';
    '        "area": AREA,';
    '        "data_format": "netcdf",';
    '        "download_format": "unarchived",';
    '    }';
    '';
    '';
    'def build_request(group, mode):';
    '    request = common_request()';
    '    request["time"] = group["times"]';
    '';
    '    if mode == "exact_date":';
    '        request["date"] = [d.strftime("%Y-%m-%d") for d in group["dates"]]';
    '        return request';
    '';
    '    if mode == "calendar":';
    '        years = sorted(set(d.year for d in group["dates"]))';
    '        months = sorted(set(d.month for d in group["dates"]))';
    '        if len(years) != 1 or len(months) != 1:';
    '            raise RuntimeError("Calendar fallback group must stay within one year-month.")';
    '        request["year"] = ["%04d" % years[0]]';
    '        request["month"] = ["%02d" % months[0]]';
    '        request["day"] = ["%02d" % d.day for d in group["dates"]]';
    '        return request';
    '';
    '    raise RuntimeError("Unknown CDS request mode: %s" % mode)';
    '';
    '';
    'def validate_batch(path, expected_epochs):';
    '    if not os.path.isfile(path) or os.path.getsize(path) <= 0:';
    '        return False';
    '';
    '    expected_ids = set(epoch_id(dt) for dt in expected_epochs)';
    '    try:';
    '        with xr.open_dataset(path) as ds:';
    '            if not dataset_has_train_fields(ds):';
    '                return False';
    '            _, actual_ids = dataset_epoch_ids(ds)';
    '            return expected_ids.issubset(set(actual_ids))';
    '    except Exception:';
    '        return False';
    '';
    '';
    'def materialize_download(download_path, final_nc):';
    '    # download_format="unarchived" should normally return one NetCDF. Keep a';
    '    # ZIP fallback so a server-side packaging change fails clearly/safely.';
    '    if zipfile.is_zipfile(download_path):';
    '        extract_dir = download_path + ".extract"';
    '        if os.path.isdir(extract_dir):';
    '            shutil.rmtree(extract_dir)';
    '        os.makedirs(extract_dir)';
    '        try:';
    '            with zipfile.ZipFile(download_path, "r") as archive:';
    '                archive.extractall(extract_dir)';
    '            nc_files = []';
    '            for root, _, files in os.walk(extract_dir):';
    '                for name in files:';
    '                    if name.lower().endswith(".nc"):';
    '                        nc_files.append(os.path.join(root, name))';
    '            if len(nc_files) != 1:';
    '                raise RuntimeError(';
    '                    "Expected one NetCDF inside CDS archive, found %d." % len(nc_files)';
    '                )';
    '            os.replace(nc_files[0], final_nc)';
    '        finally:';
    '            shutil.rmtree(extract_dir, ignore_errors=True)';
    '            if os.path.exists(download_path):';
    '                os.remove(download_path)';
    '    else:';
    '        os.replace(download_path, final_nc)';
    '';
    '';
    'def is_request_too_large(exc):';
    '    text = str(exc).lower()';
    '    patterns = (';
    '        "request too large",';
    '        "too large",';
    '        "cost limit",';
    '        "cost limits",';
    '        "request size",';
    '        "too many fields",';
    '        "maximum request",';
    '        "max request",';
    '        "http 413",';
    '        "413 client error",';
    '    )';
    '    return any(pattern in text for pattern in patterns)';
    '';
    '';
    'def describe_group(group):';
    '    dates = group["dates"]';
    '    return "%d date(s) %s..%s, time(s) %s" % (';
    '        len(dates),';
    '        dates[0].strftime("%Y-%m-%d"),';
    '        dates[-1].strftime("%Y-%m-%d"),';
    '        ",".join(group["times"]),';
    '    )';
    '';
    '';
    'def download_group(client, group, mode, stats):';
    '    final_nc = batch_path(group, mode)';
    '    partial = final_nc + ".part"';
    '';
    '    if os.path.exists(final_nc):';
    '        if validate_batch(final_nc, group["epochs"]):';
    '            print("  Reusing valid batch file: %s" % os.path.basename(final_nc))';
    '            return final_nc';
    '        quarantine(final_nc, "failed batch validation")';
    '';
    '    last_error = None';
    '    for attempt in range(1, MAX_RETRIES + 1):';
    '        if os.path.exists(partial):';
    '            os.remove(partial)';
    '';
    '        print(';
    '            "  CDS %s request attempt %d/%d: %s"';
    '            % (mode, attempt, MAX_RETRIES, describe_group(group))';
    '        )';
    '';
    '        try:';
    '            stats["retrieve_attempts"] += 1';
    '            client.retrieve(DATASET, build_request(group, mode), partial)';
    '            materialize_download(partial, final_nc)';
    '            if not validate_batch(final_nc, group["epochs"]):';
    '                quarantine(final_nc, "downloaded batch missing expected epochs/fields")';
    '                raise RuntimeError("Downloaded batch failed NetCDF validation.")';
    '            stats["successful_requests"] += 1';
    '            return final_nc';
    '        except Exception as exc:';
    '            last_error = exc';
    '            if os.path.exists(partial):';
    '                os.remove(partial)';
    '            print("  Request failed: %s" % exc)';
    '';
    '            if is_request_too_large(exc):';
    '                raise RequestTooLarge(str(exc))';
    '';
    '            if attempt < MAX_RETRIES:';
    '                wait = RETRY_WAIT_SECONDS * attempt';
    '                print("  Retrying after %d seconds..." % wait)';
    '                time.sleep(wait)';
    '';
    '    raise RuntimeError(';
    '        "CDS %s request failed after %d attempts: %s"';
    '        % (mode, MAX_RETRIES, last_error)';
    '    )';
    '';
    '';
    'def split_batch(batch_nc, group):';
    '    expected_by_id = {epoch_id(dt): dt for dt in group["epochs"]}';
    '    completed = set()';
    '';
    '    with xr.open_dataset(batch_nc) as ds:';
    '        if not dataset_has_train_fields(ds):';
    '            raise RuntimeError("Batch NetCDF is missing TRAIN-required fields.")';
    '';
    '        time_name, ids = dataset_epoch_ids(ds)';
    '        time_dims = ds[time_name].dims';
    '        if len(time_dims) != 1:';
    '            raise RuntimeError(';
    '                "Unsupported %s coordinate dimensions: %s" % (time_name, time_dims)';
    '            )';
    '        time_dim = time_dims[0]';
    '';
    '        for index, token in enumerate(ids):';
    '            if token not in expected_by_id:';
    '                continue';
    '';
    '            dt = expected_by_id[token]';
    '            target = target_path(dt)';
    '            os.makedirs(os.path.dirname(target), exist_ok=True)';
    '';
    '            if validate_train_file(target, dt):';
    '                completed.add(token)';
    '                continue';
    '';
    '            if os.path.exists(target):';
    '                quarantine(target, "failed TRAIN NetCDF validation before overwrite")';
    '';
    '            partial = target + ".part"';
    '            if os.path.exists(partial):';
    '                os.remove(partial)';
    '';
    '            # Preserve singleton time/valid_time dimension, matching current';
    '            # single-epoch CDS output and the stabilized TRAIN reader.';
    '            slice_ds = ds.isel({time_dim: [index]}).load()';
    '            try:';
    '                slice_ds.to_netcdf(partial)';
    '            finally:';
    '                slice_ds.close()';
    '';
    '            if not validate_train_file(partial, dt):';
    '                quarantine(partial, "split output failed TRAIN NetCDF validation")';
    '                raise RuntimeError("Split output validation failed for %s" % token)';
    '';
    '            os.replace(partial, target)';
    '            completed.add(token)';
    '            print("    wrote %s" % target)';
    '';
    '    missing_ids = sorted(set(expected_by_id) - completed)';
    '    if missing_ids:';
    '        raise RuntimeError(';
    '            "Batch split did not produce expected epochs: %s" % ", ".join(missing_ids)';
    '        )';
    '';
    '    for dt in group["epochs"]:';
    '        if not validate_train_file(target_path(dt), dt):';
    '            raise RuntimeError(';
    '                "Final validation failed after split: %s" % target_path(dt)';
    '            )';
    '';
    '';
    'def complete_group(client, group, mode, stats):';
    '    nc_path = download_group(client, group, mode, stats)';
    '    split_batch(nc_path, group)';
    '    if not KEEP_BATCH_FILES and os.path.exists(nc_path):';
    '        os.remove(nc_path)';
    '    print("  Batch complete.")';
    '';
    '';
    'def process_calendar_group(client, group, stats, failures, depth=0):';
    '    indent = "  " * depth';
    '    try:';
    '        complete_group(client, group, "calendar", stats)';
    '        return';
    '    except RequestTooLarge as exc:';
    '        halves = split_group(group)';
    '        if halves is None:';
    '            failures.append((group_tag(group, "calendar"), str(exc)))';
    '            print(indent + "Calendar request too large even for one date.")';
    '            return';
    '        stats["size_splits"] += 1';
    '        print(';
    '            indent';
    '            + "Calendar request exceeded CDS limits; splitting %d dates into %d + %d."';
    '            % (len(group["dates"]), len(halves[0]["dates"]), len(halves[1]["dates"]))';
    '        )';
    '        process_calendar_group(client, halves[0], stats, failures, depth + 1)';
    '        process_calendar_group(client, halves[1], stats, failures, depth + 1)';
    '    except Exception as exc:';
    '        failures.append((group_tag(group, "calendar"), str(exc)))';
    '        print(indent + "Calendar batch FAILED: %s" % exc)';
    '';
    '';
    'def process_exact_group(';
    '    client, group, state, stats, failures, number=None, total=None, depth=0';
    '):';
    '    indent = "  " * depth';
    '    if number is not None and total is not None:';
    '        print(';
    '            "\n=== Initial Batch %d/%d: %s ==="';
    '            % (number, total, describe_group(group))';
    '        )';
    '    else:';
    '        print(indent + "Adaptive subgroup: %s" % describe_group(group))';
    '';
    '    if state["exact_date_disabled"]:';
    '        print(indent + "Exact-date mode disabled for this run; using calendar fallback.")';
    '        for fallback in build_month_groups(group["epochs"]):';
    '            process_calendar_group(client, fallback, stats, failures)';
    '        return';
    '';
    '    try:';
    '        complete_group(client, group, "exact_date", stats)';
    '        return';
    '    except RequestTooLarge:';
    '        halves = split_group(group)';
    '        if halves is None:';
    '            print(indent + "Exact-date request too large even for one date; using calendar fallback.")';
    '            for fallback in build_month_groups(group["epochs"]):';
    '                process_calendar_group(client, fallback, stats, failures)';
    '            return';
    '';
    '        stats["size_splits"] += 1';
    '        print(';
    '            indent + "CDS size limit detected; adaptively splitting %d dates into %d + %d."';
    '            % (len(group["dates"]), len(halves[0]["dates"]), len(halves[1]["dates"]))';
    '        )';
    '        process_exact_group(';
    '            client, halves[0], state, stats, failures, depth=depth + 1';
    '        )';
    '        process_exact_group(';
    '            client, halves[1], state, stats, failures, depth=depth + 1';
    '        )';
    '        return';
    '    except Exception as exc:';
    '        # Current CDS web-form examples favor year/month/day/time, while the';
    '        # official cdsapi client still documents ERA5 "date" requests. If a';
    '        # server deployment rejects exact-date mode persistently, disable it';
    '        # for the remainder of this run and fall back to conservative monthly';
    '        # grouping with the current selection schema.';
    '        state["exact_date_disabled"] = True';
    '        stats["calendar_fallbacks"] += 1';
    '        print(';
    '            indent + "Exact-date mode failed persistently: %s\n"';
    '            "  Falling back to safe year/month/day/time requests for this run."';
    '            % exc';
    '        )';
    '        for fallback in build_month_groups(group["epochs"]):';
    '            process_calendar_group(client, fallback, stats, failures)';
    '';
    '';
    'def write_lines(path, lines):';
    '    with open(path, "w", encoding="utf-8") as handle:';
    '        for line in lines:';
    '            handle.write(str(line) + "\n")';
    '';
    '';
    'def final_missing(epochs):';
    '    return [dt for dt in epochs if not validate_train_file(target_path(dt), dt)]';
    '';
    '';
    'def main():';
    '    ensure_work_dir()';
    '    epochs = parse_manifest()';
    '    missing = filter_missing(epochs)';
    '';
    '    if not missing:';
    '        print("All requested ERA5 TRAIN files are already present and valid.")';
    '        status_path = os.path.join(WORK_DIR, "ERA5_download_status.txt")';
    '        write_lines(';
    '            status_path,';
    '            [';
    '                "status=complete",';
    '                "requested=%d" % len(epochs),';
    '                "missing=0",';
    '                "updated_utc=%s" % utc_now_text(),';
    '            ],';
    '        )';
    '        return 0';
    '';
    '    groups = build_exact_groups(missing)';
    '    print("Initial exact-date batches: %d" % len(groups))';
    '    print("Maximum dates/request   : %d" % MAX_DATES_PER_REQUEST)';
    '';
    '    client = cdsapi.Client()';
    '    failed_groups = []';
    '    state = {"exact_date_disabled": False}';
    '    stats = {';
    '        "retrieve_attempts": 0,';
    '        "successful_requests": 0,';
    '        "size_splits": 0,';
    '        "calendar_fallbacks": 0,';
    '    }';
    '';
    '    for number, group in enumerate(groups, 1):';
    '        process_exact_group(';
    '            client, group, state, stats, failed_groups, number, len(groups)';
    '        )';
    '';
    '    remaining = final_missing(epochs)';
    '    missing_report = os.path.join(WORK_DIR, "ERA5_missing_after_download.txt")';
    '    if remaining:';
    '        write_lines(missing_report, [epoch_id(dt) for dt in remaining])';
    '    elif os.path.exists(missing_report):';
    '        os.remove(missing_report)';
    '';
    '    status_lines = [';
    '        "status=%s" % ("complete" if not remaining else "incomplete"),';
    '        "requested=%d" % len(epochs),';
    '        "missing=%d" % len(remaining),';
    '        "failed_batches=%d" % len(failed_groups),';
    '        "initial_exact_batches=%d" % len(groups),';
    '        "successful_cds_requests=%d" % stats["successful_requests"],';
    '        "retrieve_attempts=%d" % stats["retrieve_attempts"],';
    '        "adaptive_size_splits=%d" % stats["size_splits"],';
    '        "calendar_fallbacks=%d" % stats["calendar_fallbacks"],';
    '        "updated_utc=%s" % utc_now_text(),';
    '    ]';
    '    for tag, message in failed_groups:';
    '        status_lines.append(';
    '            "failed_batch_%s=%s" % (tag, message.replace("\n", " "))';
    '        )';
    '    write_lines(os.path.join(WORK_DIR, "ERA5_download_status.txt"), status_lines)';
    '';
    '    if remaining:';
    '        print(';
    '            "\nERA5 download incomplete: %d/%d epoch(s) remain missing."';
    '            % (len(remaining), len(epochs))';
    '        )';
    '        print("Missing manifest: %s" % missing_report)';
    '        print("Re-run this same script to resume.")';
    '        return 2';
    '';
    '    print("\nAll %d requested ERA5 TRAIN files are complete and validated." % len(epochs))';
    '    print(';
    '        "CDS summary: %d successful request(s), %d retrieve attempt(s), "';
    '        "%d adaptive split(s), %d calendar fallback(s)."';
    '        % (';
    '            stats["successful_requests"],';
    '            stats["retrieve_attempts"],';
    '            stats["size_splits"],';
    '            stats["calendar_fallbacks"],';
    '        )';
    '    )';
    '    return 0';
    '';
    '';
    'if __name__ == "__main__":';
    '    sys.exit(main())';
};

