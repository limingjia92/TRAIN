function [] = generate_era5_train_script(output_dir,N,W,S,E,request_manifest)
%GENERATE_ERA5_TRAIN_SCRIPT Generate a resumable batch ERA5 downloader for TRAIN.
%
%   generate_era5_train_script(output_dir,N,W,S,E,request_manifest)
%
% INPUTS
%   output_dir       - TRAIN ERA5 root directory. Final files are written as
%                      <output_dir>/YYYYMMDD/ggapYYYYMMDDHHMM.nc
%   N,W,S,E          - CDS sub-area bounds [North, West, South, East]
%   request_manifest - Text file containing exact required ERA5 epochs, one
%                      YYYYMMDDHHMM value per line (normally ERA5_requests.txt
%                      generated by aps_era5_files.m).
%
% OUTPUT
%   Writes download_ERA5_train.py in output_dir. The Python script must be
%   reviewed and run manually:
%
%       python download_ERA5_train.py
%
% DESIGN
%   The stabilized downloader deliberately consumes exact ERA5 epochs rather
%   than reconstructing requests from acquisition dates plus two fixed hours.
%   This removes the historical 23:xx -> next-day 00:00 omission.
%
%   Current CDS requests use year/month/day/time and data_format="netcdf".
%   Exact epochs are grouped only when dates share the same year, month, and
%   identical set of required UTC hours. This avoids unwanted Cartesian
%   combinations while still reducing the number of queued CDS requests.
%
%   The generated Python script also:
%     - skips and validates already-complete TRAIN ggap*.nc files;
%     - downloads each CDS batch to a .part file and validates it;
%     - keeps a completed batch NetCDF until every requested epoch has been
%       split and validated, allowing interrupted splitting to resume;
%     - writes each final ggap*.nc atomically through a .part file;
%     - recognizes both valid_time and time, and current/legacy pressure names;
%     - retries transient request failures with bounded backoff;
%     - quarantines invalid files instead of silently overwriting/deleting them;
%     - writes ERA5_download_status.txt and, if needed,
%       ERA5_missing_after_download.txt for resumable recovery;
%     - does not suppress TLS/SSL warnings.
%
% HISTORY
%   Jan 2026  MJ  Initial TRAIN-linux batch downloader:
%                dates.txt + two fixed times, legacy CDS "date"/"format"
%                request, batch NetCDF splitting with xarray.
%
%   22/08/2026 MJ  Phase-3 stabilization for TRAIN fork:
%                - change interface to exact request manifest from Phase 2;
%                - fix cross-day requests by using exact YYYYMMDDHHMM epochs;
%                - update CDS schema to year/month/day/time + data_format and
%                  download_format;
%                - replace arbitrary 60-date batching with exact month/time-set
%                  grouping compatible with the current CDS selection schema;
%                - remove global SSL warning suppression;
%                - add current valid_time/time handling without renaming schema;
%                - add atomic download/split writes, validation and quarantine;
%                - add bounded retries and interrupted-run recovery;
%                - verify all requested epochs before deleting batch caches;
%                - add explicit final completion/missing manifests.
%
% NOTE
%   This function only GENERATES the Python downloader. It never submits a CDS
%   request itself. Python dependencies are cdsapi, xarray and pandas.
%
% See also: aps_era5_files, aps_era5_ECMWF_Python, aps_load_era.

% -------------------------------------------------------------------------
% Validate MATLAB-side inputs before writing a downloader.
% -------------------------------------------------------------------------
if nargin~=6
    error('generate_era5_train_script:InvalidInputCount', ...
        ['Expected six inputs: output_dir,N,W,S,E,request_manifest. ' ...
         'This is the stabilized Phase-3 interface.']);
end

output_dir = normalize_text_input(output_dir,'output_dir');
request_manifest = normalize_text_input(request_manifest,'request_manifest');

bounds = [N W S E];
if ~isnumeric(bounds) || numel(bounds)~=4 || any(~isfinite(double(bounds)))
    error('generate_era5_train_script:InvalidArea', ...
        'N, W, S and E must be finite numeric scalars.');
end
N = double(N);
W = double(W);
S = double(S);
E = double(E);

if N<S || N>90 || S<-90
    error('generate_era5_train_script:InvalidArea', ...
        'Latitude bounds must satisfy -90 <= S <= N <= 90.');
end

if exist(request_manifest,'file')~=2
    error('generate_era5_train_script:MissingManifest', ...
        'ERA5 request manifest does not exist: %s',request_manifest);
end

if exist(output_dir,'dir')~=7
    [status,msg] = mkdir(output_dir);
    if ~status
        error('generate_era5_train_script:CreateDirectoryFailed', ...
            'Cannot create output directory %s: %s',output_dir,msg);
    end
end

py_script_path = fullfile(output_dir,'download_ERA5_train.py');
fid = fopen(py_script_path,'w');
if fid<0
    error('generate_era5_train_script:OpenFailed', ...
        'Cannot create Python downloader: %s',py_script_path);
end

% The Python body is kept as literal lines so percent signs, braces and
% f-string-like content never become MATLAB fprintf format directives.
py_lines = {
    '#!/usr/bin/env python3';
    '"""';
    'TRAIN ERA5 batch downloader generated by generate_era5_train_script.m.';
    '';
    'Reads an exact YYYYMMDDHHMM request manifest, batches current CDS ERA5';
    'pressure-level requests, splits the returned NetCDF into TRAIN-compatible';
    'per-epoch ggap*.nc files, and safely resumes interrupted runs.';
    '"""';
    '';
    'import hashlib';
    'import os';
    'import shutil';
    'import sys';
    'import time';
    'import zipfile';
    'from collections import defaultdict';
    'from datetime import datetime';
    '';
    'try:';
    '    import cdsapi';
    '    import pandas as pd';
    '    import xarray as xr';
    'except ImportError as exc:';
    '    raise SystemExit(';
    '        "Missing Python dependency: %s. Required packages: cdsapi, xarray, pandas."';
    '        % exc';
    '    )';
    '';
    'DATASET = "reanalysis-era5-pressure-levels"';
    'WORK_DIR = @@WORK_DIR@@';
    'REQUESTS_FILE = @@REQUESTS_FILE@@';
    'AREA = [@@N@@, @@W@@, @@S@@, @@E@@]  # N, W, S, E';
    '';
    '# Current CDS NetCDF requests are deliberately kept moderate. The grouping';
    '# strategy uses one calendar month plus one identical set of UTC hours per';
    '# request, so each request is exact rather than a year/month/day Cartesian';
    '# over-selection.';
    'MAX_DAYS_PER_REQUEST = 31';
    'MAX_RETRIES = 3';
    'RETRY_WAIT_SECONDS = 30';
    'KEEP_BATCH_FILES = False';
    '';
    'VARIABLES = ["geopotential", "relative_humidity", "temperature"]';
    'PRESSURE_LEVELS = [';
    '    "1", "2", "3", "5", "7", "10", "20", "30", "50", "70",';
    '    "100", "125", "150", "175", "200", "225", "250", "300",';
    '    "350", "400", "450", "500", "550", "600", "650", "700",';
    '    "750", "775", "800", "825", "850", "875", "900", "925",';
    '    "950", "975", "1000",';
    ']';
    '';
    'TIME_ALIASES = ("valid_time", "time")';
    'PRESSURE_ALIASES = ("pressure_level", "level", "isobaricInhPa")';
    'LATITUDE_ALIASES = ("latitude", "lat")';
    'LONGITUDE_ALIASES = ("longitude", "lon")';
    'TEMP_ALIASES = ("t", "temperature")';
    'RH_ALIASES = ("r", "relative_humidity")';
    'GEOPOT_ALIASES = ("z", "geopotential")';
    '';
    '';
    'def ensure_work_dir():';
    '    os.makedirs(WORK_DIR, exist_ok=True)';
    '';
    '';
    'def parse_manifest():';
    '    if not os.path.isfile(REQUESTS_FILE):';
    '        raise RuntimeError("Request manifest not found: %s" % REQUESTS_FILE)';
    '';
    '    epochs = []';
    '    seen = set()';
    '    with open(REQUESTS_FILE, "r", encoding="utf-8") as handle:';
    '        for lineno, raw in enumerate(handle, 1):';
    '            token = raw.strip()';
    '            if not token or token.startswith("#"):';
    '                continue';
    '            if len(token) != 12 or not token.isdigit():';
    '                raise RuntimeError(';
    '                    "Invalid manifest entry at line %d: %r. Expected YYYYMMDDHHMM."';
    '                    % (lineno, token)';
    '                )';
    '            try:';
    '                dt = datetime.strptime(token, "%Y%m%d%H%M")';
    '            except ValueError as exc:';
    '                raise RuntimeError(';
    '                    "Invalid date/time at line %d: %s (%s)" % (lineno, token, exc)';
    '                )';
    '            if dt.minute != 0:';
    '                raise RuntimeError(';
    '                    "ERA5 pressure-level data are hourly; minute must be 00: %s" % token';
    '                )';
    '            if token not in seen:';
    '                seen.add(token)';
    '                epochs.append(dt)';
    '';
    '    if not epochs:';
    '        raise RuntimeError("Request manifest contains no ERA5 epochs.")';
    '';
    '    epochs.sort()';
    '    return epochs';
    '';
    '';
    'def epoch_id(dt):';
    '    return dt.strftime("%Y%m%d%H%M")';
    '';
    '';
    'def target_path(dt):';
    '    day_dir = os.path.join(WORK_DIR, dt.strftime("%Y%m%d"))';
    '    return os.path.join(day_dir, "ggap%s.nc" % epoch_id(dt))';
    '';
    '';
    'def find_name(container, aliases):';
    '    names = set(container)';
    '    for alias in aliases:';
    '        if alias in names:';
    '            return alias';
    '    return None';
    '';
    '';
    'def dataset_time_name(ds):';
    '    name = find_name(ds.coords, TIME_ALIASES)';
    '    if name is None:';
    '        name = find_name(ds.variables, TIME_ALIASES)';
    '    return name';
    '';
    '';
    'def normalize_timestamp(value):';
    '    ts = pd.Timestamp(value)';
    '    if ts.tzinfo is not None:';
    '        ts = ts.tz_convert(None)';
    '    return ts.to_pydatetime().replace(tzinfo=None)';
    '';
    '';
    'def dataset_epoch_ids(ds):';
    '    time_name = dataset_time_name(ds)';
    '    if time_name is None:';
    '        raise RuntimeError("NetCDF has neither valid_time nor time.")';
    '';
    '    values = ds[time_name].values';
    '    values = values.reshape(-1) if hasattr(values, "reshape") else [values]';
    '    ids = []';
    '    for value in values:';
    '        ids.append(epoch_id(normalize_timestamp(value)))';
    '    return time_name, ids';
    '';
    '';
    'def dataset_has_train_fields(ds):';
    '    checks = [';
    '        find_name(ds.variables, TEMP_ALIASES),';
    '        find_name(ds.variables, RH_ALIASES),';
    '        find_name(ds.variables, GEOPOT_ALIASES),';
    '        find_name(ds.variables, PRESSURE_ALIASES),';
    '        find_name(ds.variables, LATITUDE_ALIASES),';
    '        find_name(ds.variables, LONGITUDE_ALIASES),';
    '    ]';
    '    return all(name is not None for name in checks)';
    '';
    '';
    'def validate_train_file(path, expected_dt=None):';
    '    if not os.path.isfile(path) or os.path.getsize(path) <= 0:';
    '        return False';
    '';
    '    try:';
    '        with xr.open_dataset(path) as ds:';
    '            if not dataset_has_train_fields(ds):';
    '                return False';
    '            _, ids = dataset_epoch_ids(ds)';
    '            if expected_dt is not None:';
    '                expected = epoch_id(expected_dt)';
    '                if len(ids) != 1 or ids[0] != expected:';
    '                    return False';
    '        return True';
    '    except Exception:';
    '        return False';
    '';
    '';
    'def quarantine(path, reason):';
    '    if not os.path.exists(path):';
    '        return';
    '    stamp = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")';
    '    new_path = "%s.invalid_%s" % (path, stamp)';
    '    counter = 1';
    '    while os.path.exists(new_path):';
    '        new_path = "%s.invalid_%s_%d" % (path, stamp, counter)';
    '        counter += 1';
    '    os.replace(path, new_path)';
    '    print("  Quarantined invalid file (%s): %s" % (reason, new_path))';
    '';
    '';
    'def filter_missing(epochs):';
    '    missing = []';
    '    valid_existing = 0';
    '';
    '    for dt in epochs:';
    '        path = target_path(dt)';
    '        if validate_train_file(path, dt):';
    '            valid_existing += 1';
    '            continue';
    '        if os.path.exists(path):';
    '            quarantine(path, "failed TRAIN NetCDF validation")';
    '        partial = path + ".part"';
    '        if os.path.exists(partial):';
    '            os.remove(partial)';
    '        missing.append(dt)';
    '';
    '    print("Manifest epochs       : %d" % len(epochs))';
    '    print("Valid existing files  : %d" % valid_existing)';
    '    print("Epochs still missing  : %d" % len(missing))';
    '    return missing';
    '';
    '';
    'def build_groups(epochs):';
    '    # First determine the exact set of hours needed on each calendar date.';
    '    hours_by_date = defaultdict(set)';
    '    for dt in epochs:';
    '        hours_by_date[dt.date()].add(dt.strftime("%H:%M"))';
    '';
    '    # Dates can only be combined safely with current year/month/day/time CDS';
    '    # fields when they share the same year, month, and exact time set.';
    '    grouped_days = defaultdict(list)';
    '    for date_value, times in hours_by_date.items():';
    '        key = (date_value.year, date_value.month, tuple(sorted(times)))';
    '        grouped_days[key].append(date_value.day)';
    '';
    '    groups = []';
    '    for key in sorted(grouped_days):';
    '        year, month, times = key';
    '        days = sorted(set(grouped_days[key]))';
    '        for start in range(0, len(days), MAX_DAYS_PER_REQUEST):';
    '            chunk = days[start:start + MAX_DAYS_PER_REQUEST]';
    '            expected = []';
    '            for day in chunk:';
    '                for time_text in times:';
    '                    hour = int(time_text[:2])';
    '                    minute = int(time_text[3:5])';
    '                    expected.append(datetime(year, month, day, hour, minute))';
    '            expected.sort()';
    '            groups.append(';
    '                {';
    '                    "year": year,';
    '                    "month": month,';
    '                    "days": chunk,';
    '                    "times": list(times),';
    '                    "epochs": expected,';
    '                }';
    '            )';
    '    return groups';
    '';
    '';
    'def group_tag(group):';
    '    payload = ",".join(epoch_id(dt) for dt in group["epochs"]).encode("ascii")';
    '    digest = hashlib.sha1(payload).hexdigest()[:10]';
    '    return "%04d%02d_%s" % (group["year"], group["month"], digest)';
    '';
    '';
    'def batch_path(group):';
    '    return os.path.join(WORK_DIR, "era5_batch_%s.nc" % group_tag(group))';
    '';
    '';
    'def build_request(group):';
    '    return {';
    '        "product_type": ["reanalysis"],';
    '        "variable": VARIABLES,';
    '        "pressure_level": PRESSURE_LEVELS,';
    '        "year": ["%04d" % group["year"]],';
    '        "month": ["%02d" % group["month"]],';
    '        "day": ["%02d" % day for day in group["days"]],';
    '        "time": group["times"],';
    '        "area": AREA,';
    '        "data_format": "netcdf",';
    '        "download_format": "unarchived",';
    '    }';
    '';
    '';
    'def validate_batch(path, expected_epochs):';
    '    if not os.path.isfile(path) or os.path.getsize(path) <= 0:';
    '        return False';
    '';
    '    expected_ids = set(epoch_id(dt) for dt in expected_epochs)';
    '    try:';
    '        with xr.open_dataset(path) as ds:';
    '            if not dataset_has_train_fields(ds):';
    '                return False';
    '            _, actual_ids = dataset_epoch_ids(ds)';
    '            return expected_ids.issubset(set(actual_ids))';
    '    except Exception:';
    '        return False';
    '';
    '';
    'def materialize_download(download_path, final_nc):';
    '    # download_format="unarchived" should return one NetCDF file for this';
    '    # request. Keep a ZIP fallback so a server-side packaging change fails';
    '    # safely rather than being mistaken for NetCDF.';
    '    if zipfile.is_zipfile(download_path):';
    '        extract_dir = download_path + ".extract"';
    '        if os.path.isdir(extract_dir):';
    '            shutil.rmtree(extract_dir)';
    '        os.makedirs(extract_dir)';
    '        try:';
    '            with zipfile.ZipFile(download_path, "r") as archive:';
    '                archive.extractall(extract_dir)';
    '            nc_files = []';
    '            for root, _, files in os.walk(extract_dir):';
    '                for name in files:';
    '                    if name.lower().endswith(".nc"):';
    '                        nc_files.append(os.path.join(root, name))';
    '            if len(nc_files) != 1:';
    '                raise RuntimeError(';
    '                    "Expected one NetCDF inside CDS archive, found %d." % len(nc_files)';
    '                )';
    '            os.replace(nc_files[0], final_nc)';
    '        finally:';
    '            shutil.rmtree(extract_dir, ignore_errors=True)';
    '            if os.path.exists(download_path):';
    '                os.remove(download_path)';
    '    else:';
    '        os.replace(download_path, final_nc)';
    '';
    '';
    'def download_group(client, group):';
    '    final_nc = batch_path(group)';
    '    partial = final_nc + ".part"';
    '';
    '    if os.path.exists(final_nc):';
    '        if validate_batch(final_nc, group["epochs"]):';
    '            print("  Reusing valid batch file: %s" % os.path.basename(final_nc))';
    '            return final_nc';
    '        quarantine(final_nc, "failed batch validation")';
    '';
    '    last_error = None';
    '    for attempt in range(1, MAX_RETRIES + 1):';
    '        if os.path.exists(partial):';
    '            os.remove(partial)';
    '';
    '        print(';
    '            "  CDS request attempt %d/%d: %04d-%02d days=%s times=%s"';
    '            % (';
    '                attempt,';
    '                MAX_RETRIES,';
    '                group["year"],';
    '                group["month"],';
    '                ",".join("%02d" % d for d in group["days"]),';
    '                ",".join(group["times"]),';
    '            )';
    '        )';
    '';
    '        try:';
    '            client.retrieve(DATASET, build_request(group), partial)';
    '            materialize_download(partial, final_nc)';
    '            if not validate_batch(final_nc, group["epochs"]):';
    '                quarantine(final_nc, "downloaded batch missing expected epochs/fields")';
    '                raise RuntimeError("Downloaded batch failed NetCDF validation.")';
    '            return final_nc';
    '        except Exception as exc:';
    '            last_error = exc';
    '            if os.path.exists(partial):';
    '                os.remove(partial)';
    '            print("  Request failed: %s" % exc)';
    '            if attempt < MAX_RETRIES:';
    '                wait = RETRY_WAIT_SECONDS * attempt';
    '                print("  Retrying after %d seconds..." % wait)';
    '                time.sleep(wait)';
    '';
    '    raise RuntimeError(';
    '        "CDS request failed after %d attempts: %s" % (MAX_RETRIES, last_error)';
    '    )';
    '';
    '';
    'def split_batch(batch_nc, group):';
    '    expected_by_id = {epoch_id(dt): dt for dt in group["epochs"]}';
    '    completed = set()';
    '';
    '    with xr.open_dataset(batch_nc) as ds:';
    '        if not dataset_has_train_fields(ds):';
    '            raise RuntimeError("Batch NetCDF is missing TRAIN-required fields.")';
    '';
    '        time_name, ids = dataset_epoch_ids(ds)';
    '        time_dims = ds[time_name].dims';
    '        if len(time_dims) != 1:';
    '            raise RuntimeError(';
    '                "Unsupported %s coordinate dimensions: %s" % (time_name, time_dims)';
    '            )';
    '        time_dim = time_dims[0]';
    '';
    '        for index, token in enumerate(ids):';
    '            if token not in expected_by_id:';
    '                # Normally absent because grouping is exact, but ignore harmless';
    '                # extra server-returned epochs rather than writing them to TRAIN.';
    '                continue';
    '';
    '            dt = expected_by_id[token]';
    '            target = target_path(dt)';
    '            os.makedirs(os.path.dirname(target), exist_ok=True)';
    '';
    '            if validate_train_file(target, dt):';
    '                completed.add(token)';
    '                continue';
    '';
    '            if os.path.exists(target):';
    '                quarantine(target, "failed TRAIN NetCDF validation before overwrite")';
    '';
    '            partial = target + ".part"';
    '            if os.path.exists(partial):';
    '                os.remove(partial)';
    '';
    '            # List indexing preserves the singleton time/valid_time dimension,';
    '            # which matches TRAIN files generated by single-epoch CDS requests.';
    '            slice_ds = ds.isel({time_dim: [index]}).load()';
    '            try:';
    '                slice_ds.to_netcdf(partial)';
    '            finally:';
    '                slice_ds.close()';
    '';
    '            if not validate_train_file(partial, dt):';
    '                quarantine(partial, "split output failed TRAIN NetCDF validation")';
    '                raise RuntimeError("Split output validation failed for %s" % token)';
    '';
    '            os.replace(partial, target)';
    '            completed.add(token)';
    '            print("    wrote %s" % target)';
    '';
    '    missing_ids = sorted(set(expected_by_id) - completed)';
    '    if missing_ids:';
    '        raise RuntimeError(';
    '            "Batch split did not produce expected epochs: %s" % ", ".join(missing_ids)';
    '        )';
    '';
    '    # Revalidate final products before the batch cache is removed.';
    '    for dt in group["epochs"]:';
    '        if not validate_train_file(target_path(dt), dt):';
    '            raise RuntimeError(';
    '                "Final validation failed after split: %s" % target_path(dt)';
    '            )';
    '';
    '';
    'def write_lines(path, lines):';
    '    with open(path, "w", encoding="utf-8") as handle:';
    '        for line in lines:';
    '            handle.write(str(line) + "\n")';
    '';
    '';
    'def final_missing(epochs):';
    '    return [dt for dt in epochs if not validate_train_file(target_path(dt), dt)]';
    '';
    '';
    'def main():';
    '    ensure_work_dir()';
    '    epochs = parse_manifest()';
    '    missing = filter_missing(epochs)';
    '';
    '    if not missing:';
    '        print("All requested ERA5 TRAIN files are already present and valid.")';
    '        status_path = os.path.join(WORK_DIR, "ERA5_download_status.txt")';
    '        write_lines(';
    '            status_path,';
    '            [';
    '                "status=complete",';
    '                "requested=%d" % len(epochs),';
    '                "missing=0",';
    '                "updated_utc=%s" % datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),';
    '            ],';
    '        )';
    '        return 0';
    '';
    '    groups = build_groups(missing)';
    '    print("CDS batch requests     : %d" % len(groups))';
    '';
    '    client = cdsapi.Client()';
    '    failed_groups = []';
    '';
    '    for number, group in enumerate(groups, 1):';
    '        print(';
